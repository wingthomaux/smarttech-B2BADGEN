import publications from "../public/data/publications.json";
import publicationUpdates from "../public/data/publications-update-2026-09-07.json";
import {catalog} from "./catalog";
import {slugify} from "./catalog-paths";
import {portalProfiles} from "./portal-profiles";
export {editorialEntriesForPortal,editorialEntriesForProvider} from "./editorial-portals";
export {portalProfiles} from "./portal-profiles";
export function portalPath(name:string,locale:"de"|"en"="de"){return `${locale==="en"?"/en/portals":"/portale"}/${slugify(name)}`}
const sourceUrls=new Map(portalProfiles.map(portal=>[portal.name,new Set([...publications,...publicationUpdates].filter(item=>item.p.includes(portal.name)).map(item=>item.u))]));
export function portalArticles(name:string){return catalog.knowledge.filter(item=>item.sourcePortals?.includes(name)||sourceUrls.get(name)?.has(item.url)).sort((a,b)=>(b.datePublished||"").localeCompare(a.datePublished||"")||a.title.localeCompare(b.title,"de")||a.id-b.id)}
export function getPortal(slug:string){return portalProfiles.find(portal=>slugify(portal.name)===slug)}
