const legalSuffix=/\s+(?:GmbH|AG|SE|Inc\.?|Ltd\.?|Limited|B\.?V\.?|S\.?A\.?|Corp\.?|Corporation)$/i;

export function providerFamily(raw:string){
  const name=raw.replace(/\s+/g," ").trim();
  if(exactAliases[name])return exactAliases[name];
  for(const [pattern,family] of familyRules)if(pattern.test(name))return family;
  const stripped=name.replace(legalSuffix,"").replace(/[,.\s]+$/,"").trim();
  return exactAliases[stripped]||stripped;
}
